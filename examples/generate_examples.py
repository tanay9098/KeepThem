"""Regenerate examples/example_queries.md from REAL runs against a fresh, throw-away graph.

    python examples/generate_examples.py

Keeping the doc generated means the "expected output" can never drift from the code.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from keepthem import config  # noqa: E402

config.GRAPH_NAME = "keepthem_examples"          # never touch the user's own graph
config.EMBEDDED_PATH = ".keepthem/examples.rdb"

from keepthem import seed, tools  # noqa: E402
from keepthem.agent import OfflineAgent  # noqa: E402
from keepthem.db import get_kg  # noqa: E402

PROMPTS = [
    ("Investigate a team", "Investigate attrition risk on the Platform team"),
    ("Investigate one person", "What is Victor Alvarez's attrition risk?"),
    ("Manager load (degree centrality)", "Which managers are overloaded?"),
    ("Attrition clusters (label propagation)", "Show attrition clusters"),
    ("Explain a conclusion", "Why is Dana Ruiz high risk?"),
    ("Explain a past decision", "What happened after D-001? Explain it."),
    ("Write back to the graph", "Log a completed stay interview for Dana Ruiz"),
]


def main() -> None:
    kg = get_kg()
    seed.seed(kg, verbose=False)
    out = ["# Example queries and expected outputs", "",
           "_Generated by `examples/generate_examples.py` from a fresh seed (as-of "
           f"{config.AS_OF}); regenerate it rather than editing by hand._", "",
           f"Backend used: {kg.backend}", ""]
    agent = OfflineAgent(kg)
    for title, prompt in PROMPTS:
        out += [f"## {title}", "", f"**Ask:** `{prompt}`", ""]
        calls, final = [], ""
        for ev in agent.run(prompt):
            if ev["type"] == "tool_call":
                calls.append(f"`{ev['name']}({json.dumps(ev['input'])})`")
            elif ev["type"] == "final":
                final = ev["text"]
        out += ["**Tool calls:** " + " → ".join(calls), "", "**Output:**", "", final, "", "---", ""]

    out += ["## The Cypher behind a conclusion", "",
            "`explain_decision` returns, for every point of the score, the Cypher that produced it. "
            "For Dana Ruiz's *manager overload* signal:", ""]
    r = tools.explain_decision("Why is Dana Ruiz high risk?", kg=kg)
    for q in [q for q in r["queries"] if q["name"].startswith("overloaded_manager")]:
        out += [f"_{q['name']}_", "```cypher", q["cypher"], "```", f"params: `{json.dumps(q['params'])}`", ""]

    out += ["## Raw Cypher you can paste into FalkorDB Browser (http://localhost:3000)", "",
            "```cypher",
            "// The whole story around Dana: everything within 2 hops",
            "MATCH p=(:Employee {name:'Dana Ruiz'})-[*1..2]-() RETURN p LIMIT 100;", "",
            "// Who resigned, and what did they have in common?",
            "MATCH p=(x:Employee {status:'left'})-[:WORKED_ON]->(pr:Project) RETURN p;", "",
            "// Root cause chain: director -> denied backfill -> manager -> reports",
            "MATCH p=(h:Manager)-[:MADE]->(:Decision {type:'headcount_denied'})-[:AFFECTED]->(m:Manager)<-[:REPORTS_TO]-(e) RETURN p;", "",
            "// Overloaded managers (degree centrality on REPORTS_TO)",
            "MATCH (m:Manager)<-[:REPORTS_TO]-(e:Employee {status:'active'}) RETURN m.name, count(e) AS reports ORDER BY reports DESC;", "",
            "// Native FalkorDB algorithm: PageRank over the reporting tree",
            "CALL algo.pageRank('Employee','REPORTS_TO') YIELD node, score RETURN node.name, score ORDER BY score DESC LIMIT 5;",
            "```", ""]
    path = pathlib.Path(__file__).with_name("example_queries.md")
    path.write_text("\n".join(out))
    kg.delete()
    print("wrote", path)


if __name__ == "__main__":
    main()
